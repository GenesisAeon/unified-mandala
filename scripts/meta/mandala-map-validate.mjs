#!/usr/bin/env node
// Gentle validator for MandalaMap.yaml/json coherence. Non-blocking.
import fs from 'node:fs';
import path from 'node:path';
import YAML from 'yaml';

const root = process.cwd();
const yamlPath = path.join(root, 'MandalaMap.yaml');
const jsonPath = path.join(root, 'MandalaMap.json');
const mdPath = path.join(root, 'MandalaMap.md');

function exists(p) {
  try {
    fs.accessSync(p, fs.constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

function readYaml(p) {
  try {
    return YAML.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    return undefined;
  }
}

function readJson(p) {
  try {
    return JSON.parse(fs.readFileSync(p, 'utf8'));
  } catch {
    return undefined;
  }
}

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (value && typeof value === 'object') {
    const out = {};
    for (const k of Object.keys(value).sort()) out[k] = stable(value[k]);
    return out;
  }
  return value;
}

function diffSummary(a, b) {
  const sa = JSON.stringify(stable(a));
  const sb = JSON.stringify(stable(b));
  if (sa === sb) return { equal: true };
  // Simple string diff length metric (gentle)
  const lenA = sa.length,
    lenB = sb.length;
  const delta = Math.abs(lenA - lenB);
  return { equal: false, deltaChars: delta, lenA, lenB };
}

function main() {
  const hasYaml = exists(yamlPath);
  const hasJson = exists(jsonPath);
  const hasMd = exists(mdPath);

  if (!hasYaml && !hasJson && !hasMd) {
    console.log('[mandala:validate] No MandalaMap files found.');
    return;
  }

  let issues = 0;

  if (!hasYaml) {
    console.log('[mandala:validate] Missing MandalaMap.yaml');
    issues++;
  }
  if (!hasJson) {
    console.log('[mandala:validate] Missing MandalaMap.json');
    issues++;
  }
  if (!hasMd) {
    console.log('[mandala:validate] Missing MandalaMap.md');
    issues++;
  }

  if (hasYaml && hasJson) {
    const y = readYaml(yamlPath);
    const j = readJson(jsonPath);
    if (y === undefined) {
      console.log('[mandala:validate] Failed to parse MandalaMap.yaml');
      issues++;
    }
    if (j === undefined) {
      console.log('[mandala:validate] Failed to parse MandalaMap.json');
      issues++;
    }
    if (y !== undefined && j !== undefined) {
      const sum = diffSummary(y, j);
      if (sum.equal) {
        console.log('[mandala:validate] YAML and JSON are consistent.');
      } else {
        console.log(
          `[mandala:validate] YAML/JSON differ (Δ≈${sum.deltaChars} chars; yaml:${sum.lenA}, json:${sum.lenB}).`,
        );
        console.log(
          '[mandala:validate] Tip: run "pnpm meta:mandala:sync" to sync JSON from YAML and refresh MD summary.',
        );
        issues++;
      }

      // Check legend/category/status coherence
      const entries = Array.isArray(y?.entries) ? y.entries : [];
      const cats = new Set(Object.keys(y?.legend?.categories ?? {}));
      const stats = new Set(Object.keys(y?.legend?.status ?? {}));
      let missingFields = 0,
        badCats = 0,
        badStats = 0;
      for (const e of entries) {
        if (!e || typeof e !== 'object') {
          missingFields++;
          continue;
        }
        if (!('path' in e) || !('category' in e) || !('status' in e)) missingFields++;
        if (e.category && !cats.has(e.category)) badCats++;
        if (e.status && !stats.has(e.status)) badStats++;
      }
      if (missingFields)
        console.log(
          `[mandala:validate] Entries with missing required fields (path/category/status): ${missingFields}`,
        );
      if (badCats)
        console.log(`[mandala:validate] Entries referencing undefined categories: ${badCats}`);
      if (badStats)
        console.log(`[mandala:validate] Entries referencing undefined statuses: ${badStats}`);
      if (missingFields || badCats || badStats) issues++;
    }
  }

  if (hasMd) {
    // Gentle presence check only; content is regenerated by sync script
    console.log('[mandala:validate] MandalaMap.md present.');
  }

  if (issues === 0) {
    console.log('[mandala:validate] OK');
  } else {
    // Non-blocking
  }
}

main();
